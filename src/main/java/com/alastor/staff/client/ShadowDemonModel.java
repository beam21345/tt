    @Override
    public void setupAnim(ShadowDemonEntity e, float limbSwing, float limbSwingAmount, float age, float netHeadYaw, float headPitch) {
        this.root().getAllParts().forEach(ModelPart::resetPose);
        float breathe = Mth.sin(age * 0.09f);
        float walk = limbSwing * 0.5f;
        float amt = Math.min(1f, limbSwingAmount);

        body.xRot += breathe * 0.05f + amt * 0.12f;
        body.zRot += Mth.cos(walk) * 0.07f * amt;
        body.y += -Math.abs(Mth.sin(walk)) * 1.2f * amt;
        neck.xRot += breathe * 0.04f;
        head.yRot = netHeadYaw * Mth.DEG_TO_RAD * 0.8f;
        head.xRot += headPitch * Mth.DEG_TO_RAD * 0.5f;
        head.zRot = Mth.sin(age * 0.035f) * 0.15f;                    // unsettling slow head tilt
        jaw.xRot += 0.1f + Math.max(0f, Mth.sin(age * 0.11f)) * 0.25f; // jaw working, teeth bared

        // tail swishes in a slow S
        tail.yRot = Mth.sin(age * 0.08f) * 0.35f;
        tail2.yRot = Mth.sin(age * 0.08f - 0.8f) * 0.4f;
        tail3.yRot = Mth.sin(age * 0.08f - 1.6f) * 0.45f;
        tail.xRot += amt * 0.3f;

        for (int i = 0; i < 2; i++) {
            float s = i == 0 ? 1f : -1f;   // _r / _l mirror
            float ph = i == 0 ? Mth.PI : 0f;
            // wings half-folded, slowly breathing open and shut, spreading wider when moving
            float flap = Mth.sin(age * 0.07f + i * 0.3f);
            wing[i].yRot += s * (flap * 0.12f + amt * 0.25f);
            wing[i].zRot += s * flap * 0.06f;
            wingTip[i].zRot += s * (0.1f + flap * 0.15f);
            // long arms hang and sway, swinging opposite to the legs
            arm[i].xRot = Mth.cos(walk + ph) * 0.65f * amt - 0.3f + Mth.sin(age * 0.08f + i) * 0.06f;
            arm[i].zRot += s * Mth.sin(age * 0.06f) * 0.05f;
            forearm[i].xRot = -0.45f - Mth.sin(age * 0.07f + i) * 0.08f;
            hand[i].xRot = -0.25f;
            // prowling digitigrade gait
            leg[i].xRot += Mth.cos(walk + ph) * 0.8f * amt;
            shin[i].xRot += Math.max(0f, -Mth.sin(walk + ph)) * 0.7f * amt;
            foot[i].xRot += Math.max(0f, Mth.sin(walk + ph)) * 0.4f * amt;
        }

        // attack: rears up, spreads its wings, rakes down with both claws and snaps its jaw
        if (this.attackTime > 0f) {
            float t = this.attackTime;
            float swing = Mth.sin(t * Mth.PI);
            arm[0].xRot = -2.7f * swing + 0.4f * t;
            arm[0].yRot = 0.4f * swing;
            arm[1].xRot = -2.3f * Mth.sin(Math.min(1f, t * 1.3f) * Mth.PI);
            arm[1].yRot = -0.3f * swing;
            forearm[0].xRot = -0.2f;
            forearm[1].xRot = -0.3f;
            body.xRot += 0.35f * swing - 0.15f * (1 - t);
            jaw.xRot = 0.15f + 0.7f * swing;
            for (int i = 0; i < 2; i++) wing[i].yRot += (i == 0 ? 1f : -1f) * 0.6f * swing;
        }
    }
